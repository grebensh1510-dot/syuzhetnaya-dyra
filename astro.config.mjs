import { defineConfig } from 'astro/config';

// Сборка для предпросмотра отличается одним: страницы кладутся файлами
// (ionych/dosye.html), а не каталогами с index.html. В предпросмотре сайт
// лежит в подпапке чужого домена, и полагаться на то, что сервер отдаст
// каталог как index.html, нельзя — каждая ссылка должна вести в файл,
// который действительно опубликован. Адреса потом переписывает
// scripts/build-preview.mjs.
const preview = process.env.PUBLIC_PREVIEW === '1';

/*
 * Адрес сайта нужен ровно для одного: карточки ссылки. og:image обязан быть
 * абсолютным — мессенджеры и соцсети относительный путь не подхватят.
 *
 * Берётся из переменной окружения, а не зашит: на хостинге он один, в
 * предпросмотре другой, локально его нет вовсе. Пока переменной нет, Shell
 * просто не выводит теги карточки — страница от этого не ломается.
 *
 * На Cloudflare Pages задаётся в Settings → Variables: SITE_URL.
 */
const site = process.env.SITE_URL || undefined;

export default defineConfig({
  site,
  server: { port: 4321 },
  devToolbar: { enabled: false },
  build: {
    format: preview ? 'file' : 'directory',
    // Имена, начинающиеся с подчёркивания, площадка предпросмотра оставляет
    // за собой, поэтому там папка ассетов называется иначе. paths.js считает
    // корень как «на уровень вверх от собственного файла» — ему всё равно,
    // как называется папка.
    assets: preview ? 'astro' : '_astro',
  },
  vite: {
    build: {
      // three.js весит своё; предупреждение о размере чанка тут не новость.
      chunkSizeWarningLimit: 900,
    },
  },
});
