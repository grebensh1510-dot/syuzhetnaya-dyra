// Внутренние адреса, которые собирает JS.
//
// На обычном хостинге сайт лежит в корне домена, и адрес — просто
// «/ionych/dyra/». В предпросмотре он лежит в подпапке чужого домена: там
// ведущий слеш уводит из сайта наружу.
//
// У предпросмотра своя сборка (PUBLIC_PREVIEW=1), и в ней все страницы лежат
// одним уровнем: ionych-dyra.html, ionych-dosye-starcev.html. Не из любви к
// плоскому — иначе на страницах разной глубины адрес одной и той же таблицы
// стилей записан по-разному («./_astro/…» против «../../_astro/…»), и при
// переходе лепестками ссылка успевает разрешиться от старого адреса: новая
// страница открывается без стилей. Один уровень — один и тот же адрес у всех.
//
// Корень модуль считает от собственного адреса: бандлы лежат в
// <корень>/_astro/, значит на уровень вверх — корень.
//
// Разметка обходится без этого: её адреса переписывает
// scripts/build-preview.mjs уже по готовым файлам. Здесь — только то, что
// строится во время работы.

const PREVIEW = import.meta.env.PUBLIC_PREVIEW === '1';

const ROOT = import.meta.env.DEV ? '/' : new URL('../', import.meta.url).href;

export function to(path) {
  if (!PREVIEW) return `/${path}`;
  const [p, q] = path.split('?');
  const file = `${p.replace(/^\/|\/$/g, '').replace(/\//g, '-')}.html`;
  return ROOT + file + (q ? `?${q}` : '');
}
